/* FastML native parameter-file generator for browser/Node WASM integration.
 * Mirrors FastMLWrapper.py's param.file construction; does not run binaries.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.FastMLPrepare = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  const MODELS = Object.freeze({
    JTT: 'JTT', LG: 'LG', cpREV: 'CPREV', mtREV: 'REV', WAG: 'WAG',
    Dayhoff: 'DAY', MIX: 'MIX', JC_Nuc: 'NUCJC',
    T92: 'TAMURA92', HKY: 'HKY', empiriCodon: 'EMPIRICODON',
    yang: 'NYCODON'
  });

  // The Python wrapper takes the first two whitespace-separated words per line.
  function parsePreParam(content) {
    if (typeof content !== 'string') throw new TypeError('pre.param must be text');
    const values = {};
    for (const line of content.split(/\r?\n/)) {
      const tokens = line.trim().split(/\s+/);
      if (tokens.length > 1) values[tokens[0]] = tokens[1];
    }
    return values;
  }

  function safePath(path, field) {
    if (typeof path !== 'string' || !path || /[\r\n\s]/.test(path)) {
      throw new Error(`${field} must be a nonempty path without whitespace`);
    }
    return path;
  }

  function join(dir, name) {
    return `${dir.replace(/\/$/, '')}/${name}`;
  }

  // Avoid native FastML optimization paths that currently exit or return no likelihood.
  function validateFastMLOptions(preParam) {
    const p = typeof preParam === 'string' ? parsePreParam(preParam) : preParam;
    if (!p || typeof p !== 'object') throw new TypeError('preParam must be text or an object');
    const branch = p.branch === 'on';
    const gamma = p.gamma !== 'off';
    const optimizeAlpha = !p.alpha || p.alpha === 'optimize';
    if (!branch && gamma && optimizeAlpha) {
      throw new Error('Optimizing gamma requires branch-length optimization. Enable Optimize Branch Lengths, disable Gamma Distribution, or provide a fixed alpha.');
    }
    if (['JC_Nuc', 'T92', 'HKY'].includes(p.model)) {
      if (!branch || !gamma) {
        throw new Error('This FastML build currently supports nucleotide reconstruction only with both Optimize Branch Lengths and Use Gamma Distribution enabled. Other paths require native C++ repairs.');
      }
      if (p.model === 'T92' || p.model === 'HKY') {
        throw new Error(`${p.model === 'T92' ? 'T92' : 'HKY85'} is not yet supported reliably in this FastML WASM build: its native parameter-optimization path is incomplete.`);
      }
    }
  }

  /**
   * @param {string|object} preParam - pre.param text or parsed key/value object
   * @param {object} options
   * @param {string} [options.workDir='/results'] - virtual WASM working directory
   * @param {string} [options.treePath] - unrooted tree to be generated by unroot WASM
   * @param {string} [options.msaPath] - aligned FASTA consumed by FastML WASM
   * @param {string} [options.weightsPath] - existing/generated MIX weights file
   * @returns {string} native param.file contents (with terminating newline)
   */
  function prepareFastMLParams(preParam, options = {}) {
    const p = typeof preParam === 'string' ? parsePreParam(preParam) : preParam;
    if (!p || typeof p !== 'object') throw new TypeError('preParam must be text or an object');
    validateFastMLOptions(p);
    const wd = safePath(options.workDir || '/results', 'workDir');
    const model = MODELS[p.model];
    if (!model) throw new Error(`Unsupported model: ${String(p.model)}`);

    // Both files must be created in the Emscripten filesystem before executing FastML.
    const tree = safePath(options.treePath || join(wd, 'unrooted_tree.txt'), 'treePath');
    const msa = safePath(options.msaPath ||
      (p.isAligned === 'aligned' ? p.msa : join(wd, 'aligned.msa')), 'msaPath');
    const joint = p.joint === 'on';
    const gamma = p.gamma !== 'off';

    const lines = [
      `treefile ${tree}`,
      `seqfile ${msa}`,
      `modelName ${model}`
    ];

    if (model === 'MIX') {
      if (!options.weightsPath) {
        throw new Error('MIX requires weightsPath; generating weights is a separate step');
      }
      lines.push(`Modelweightsfile ${safePath(options.weightsPath, 'weightsPath')}`);
    }

    lines.push(`doJoint ${joint ? 1 : 0}`);
    lines.push(`optimizeBrLenOnStartingTree ${p.branch === 'on' ? 1 : 0}`);

    const outputs = [
      'outTreeFileNewick', 'outTreeFileAncestor', 'outFile_prob_marginal',
      'outFile_seq_marginal', 'reportFile'
    ];
    if (joint) outputs.push('outFile_prob_joint', 'outFile_seq_joint');
    for (const output of outputs) lines.push(`${output} ${join(wd, output)}.txt`);

    lines.push('seqOutputFormat fasta');
    lines.push(`distributionName ${gamma ? 'gam' : 'hom'}`);
    if (gamma) {
      // Matches the Python wrapper exactly, including its numeric-alpha behavior.
      lines.push('userProvideAlpha 0');
      if (p.alpha && p.alpha !== 'optimize') {
        if (!Number.isFinite(Number(p.alpha)) || Number(p.alpha) <= 0) {
          throw new Error('Numeric alpha must be positive');
        }
        lines.push(`gammaPar ${p.alpha}`);
      }
    }
    return lines.join('\n') + '\n';
  }

  /** Write the generated file to an Emscripten module's virtual filesystem. */
  function writeFastMLParams(module, preParam, options = {}) {
    if (!module || !module.FS || typeof module.FS.writeFile !== 'function') {
      throw new Error('A module with FS.writeFile is required');
    }
    const workDir = options.workDir || '/results';
    const content = prepareFastMLParams(preParam, options);
    const path = join(workDir, 'param.file');
    module.FS.writeFile(path, content);
    return path;
  }

  return { MODELS, parsePreParam, validateFastMLOptions, prepareFastMLParams, writeFastMLParams };
});
